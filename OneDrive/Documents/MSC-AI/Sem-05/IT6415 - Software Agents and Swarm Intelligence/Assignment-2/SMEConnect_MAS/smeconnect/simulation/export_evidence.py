"""Export measured, reproducible Phase 05.2 evidence for the MSc report.

Run from the repository directory:
    python -m smeconnect.simulation.export_evidence --out-dir evaluation_output

Output is synthetic simulation data, not real market data.
"""
import argparse
import csv
import json
import platform
import subprocess
from datetime import datetime, timezone
from importlib import metadata
from pathlib import Path

from smeconnect.simulation.experiment_evaluation import (
    flat_trial_rows,
    run_experiment_batch,
)


def _revision() -> str:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True,
            check=False, timeout=5,
        )
        return result.stdout.strip() if result.returncode == 0 else "not available"
    except (FileNotFoundError, subprocess.SubprocessError):
        return "not available"


def _version(package: str) -> str:
    try:
        return metadata.version(package)
    except metadata.PackageNotFoundError:
        return "not installed"


def _format(number, *, percent=False, money=False):
    if number is None:
        return "N/A"
    if percent:
        return f"{number:.2f}%"
    if money:
        return f"Rs. {number:,.2f}"
    return str(number)


def render_results_markdown(batch: dict) -> str:
    """Render actual batch summary; do not invent results."""
    config = batch["config"]
    lines = [
        "# Verified-by-execution synthetic evaluation output",
        "",
        "> Values below were generated by running the project's synthetic MAS model.",
        "> They are not empirical observations from real SMEs or evidence of learning.",
        "",
        f"- Paired comparisons: **{config['paired_trials']}**",
        f"- Independent supplier-selection executions: **{config['snapshot_runs']}**",
        f"- Retailer: **{config['retailer']}**",
        f"- Order quantities: **{config['quantities']}**",
        f"- Initial offered prices: **{config['initial_prices']}**",
        f"- Preferred price: **Rs. {config['retailer_target']:.2f}**",
        f"- Maximum negotiation rounds: **{config['max_rounds']}**",
        "",
        "## Results by market scenario",
        "",
        "| Scenario | Pairs | Supplier switches | Switch rate | Normal selection | Changed selection | Normal mean gross profit | Changed mean gross profit |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in batch["summary"]:
        lines.append(
            f"| {row['scenario_name']} | {row['paired_trials']} | {row['supplier_switches']} "
            f"| {_format(row['supplier_switch_rate_pct'], percent=True)} "
            f"| {_format(row['normal']['selection_rate_pct'], percent=True)} "
            f"| {_format(row['changed']['selection_rate_pct'], percent=True)} "
            f"| {_format(row['normal']['mean_expected_gross_profit_rs'], money=True)} "
            f"| {_format(row['changed']['mean_expected_gross_profit_rs'], money=True)} |"
        )
    lines += [
        "",
        "## Messages and negotiation rounds",
        "",
        "| Scenario | Normal messages/trial | Changed messages/trial | Normal rounds/trial | Changed rounds/trial |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in batch["summary"]:
        lines.append(
            f"| {row['scenario_name']} "
            f"| {row['normal']['mean_messages_per_trial']:.2f} "
            f"| {row['changed']['mean_messages_per_trial']:.2f} "
            f"| {row['normal']['mean_negotiation_rounds_per_trial']:.2f} "
            f"| {row['changed']['mean_negotiation_rounds_per_trial']:.2f} |"
        )
    lines += [
        "",
        "## Interpretation boundaries",
        "",
        batch["limitations"],
        "",
        "Supplier switching means selection IDs differ in paired conditions; it does not "
        "prove online learning or emergent self-organization. Expected gross profit "
        "excludes delivery and operating costs. Negotiations are sequential simulations.",
        "",
        "## Reporting instruction",
        "",
        "Copy these tables into Section 6 of docs/FINAL_ASSIGNMENT_REPORT.md "
        "only after confirming the local test suite passed and preserving exported files.",
        "",
    ]
    return "\n".join(lines)


def render_completed_report(batch: dict, *, template: str) -> str:
    """Insert measured synthetic results into a separate, reviewable report copy."""
    opening = "<!-- PHASE05_RESULTS_START -->"
    closing = "<!-- PHASE05_RESULTS_END -->"
    if template.count(opening) != 1 or template.count(closing) != 1:
        raise ValueError("Report template is missing unique evidence markers.")
    before, remaining = template.split(opening, 1)
    _, after = remaining.split(closing, 1)
    section = render_results_markdown(batch)
    # A generated report already contains the tables; omit copy instructions.
    section = section.split("## Reporting instruction", 1)[0].rstrip() + "\\n"
    section = section.replace(
        "# Verified-by-execution synthetic evaluation output",
        "### 6.1 Measured synthetic evaluation (local execution)",
    ).replace("## Results by market scenario", "#### Results by market scenario"
    ).replace("## Messages and negotiation rounds", "#### Messages and negotiation rounds"
    ).replace("## Interpretation boundaries", "#### Interpretation boundaries"
    ).replace("## Reporting instruction", "#### Reporting instruction")
    completed = before + section + after
    completed = completed.replace(
        "## 6. Results — Verification Required",
        "## 6. Results — Locally Measured Synthetic Simulation",
    ).replace(
        "replace the results placeholders with verified local experiment outputs before submission.",
        "contains results generated from a local synthetic simulation; review pytest and provenance before submission.",
    )
    return completed.replace(
        "- [ ] Insert the generated measured-results table into Section 6",
        "- [x] Measured synthetic results inserted into Section 6 by the evidence exporter",
    )


def export_evidence(out_dir: Path, *, batch: dict | None = None) -> dict[str, Path]:
    """Write reviewable evidence files only inside an explicit local output directory."""
    output = Path(out_dir)
    if output.exists() and not output.is_dir():
        raise ValueError("Output path must be a directory.")
    output.mkdir(parents=True, exist_ok=True)
    if batch is None:
        batch = run_experiment_batch()
    trials = flat_trial_rows(batch)
    if not trials:
        raise ValueError("Experiment returned no trial rows.")
    manifest = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "source_git_commit": _revision(),
        "python": platform.python_version(),
        "packages": {
            "langgraph": _version("langgraph"),
            "pydantic": _version("pydantic"),
            "streamlit": _version("streamlit"),
            "pytest": _version("pytest"),
        },
        "config": batch["config"],
        "summary": batch["summary"],
        "limitations": batch["limitations"],
        "status": "generated_from_executed_synthetic_simulation",
    }
    paths = {
        "csv": output / "phase05_trials.csv",
        "json": output / "phase05_summary.json",
        "markdown": output / "RESULTS_FOR_REPORT.md",
        "report": output / "FINAL_REPORT_WITH_RESULTS.md",
    }
    with paths["csv"].open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(trials[0]))
        writer.writeheader()
        writer.writerows(trials)
    paths["json"].write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    paths["markdown"].write_text(render_results_markdown(batch), encoding="utf-8")
    template_path = Path(__file__).resolve().parents[2] / "docs" / "FINAL_ASSIGNMENT_REPORT.md"
    if not template_path.is_file():
        raise FileNotFoundError(f"Report template missing: {template_path}")
    completed = render_completed_report(
        batch, template=template_path.read_text(encoding="utf-8"),
    )
    paths["report"].write_text(completed, encoding="utf-8")
    return paths


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate measured synthetic evaluation evidence for MSc assignment"
    )
    parser.add_argument("--out-dir", default="evaluation_output",
                        help="Directory for the generated local CSV, JSON and Markdown files")
    args = parser.parse_args(argv)
    paths = export_evidence(Path(args.out_dir))
    print("Synthetic Phase 05.2 evaluation completed.")
    for label, path in paths.items():
        print(f"{label}: {path.resolve()}")
    print("Review the output and pytest result before claiming the findings in your report.")


if __name__ == "__main__":
    main()
